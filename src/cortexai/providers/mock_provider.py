"""Mock provider implementation for testing without real LLM API calls."""

import random
import re
import json
from typing import Union, List, Dict, Optional, Any

from .base_provider import BaseProvider
from ..tools.base_tool import BaseTool
from ..core.logging import get_logger

logger = get_logger("providers.mock_provider")


class MockProvider(BaseProvider):
    """
    A mock provider for testing and demos without requiring API keys.

    This provider can simulate responses including tool calls based on patterns
    in the input or randomly. It's useful for testing agent logic, tool usage,
    and conversation flows without real API costs.
    
    Usage:
        provider = MockProvider(seed=42)
        agent = Agent(provider=provider, tools=[...])
        result = agent.run_with_tools("Research quantum computing")
    """

    is_chat_model = True

    def __init__(self, seed: Optional[int] = None, scripted_responses: Dict[str, str] = None):
        """
        Initialize the mock provider.

        Args:
            seed: Optional random seed for reproducible outputs. If None,
                responses will have more randomness.
            scripted_responses: Optional dictionary mapping prompt substrings 
                to specific responses for deterministic testing.
        """
        if seed is not None:
            random.seed(seed)

        self.scripted_responses = scripted_responses or {}
        
        # Default responses when no scripted response matches
        self.responses = [
            "This is a mock response. In a real system, this would be generated by an LLM.",
            "I would recommend researching that topic further to get more comprehensive information.",
            "Based on the available information, I can't provide a definitive answer.",
            "Let me analyze that for you... The key insights are: 1) data shows trends, 2) multiple factors involved."
        ]

        # Pre-defined tool call templates for common tools
        self.tool_calls = {
            "WebSearchTool": {
                "name": "WebSearchTool",
                "arguments": {"query": "sample search", "num_results": 3}
            },
            "FileReaderTool": {
                "name": "FileReaderTool",
                "arguments": {"file_path": "sample.txt"}
            },
            "FileWriterTool": {
                "name": "FileWriterTool",
                "arguments": {"file_path": "output.txt", "content": "Sample content", "mode": "w"}
            },
            "BrowserTool": {
                "name": "BrowserTool",
                "arguments": {"action": "navigate", "url": "https://example.com"}
            },
        }
        
        # Track call history for debugging and testing
        self.call_history = []
        
        logger.info(f"Initialized MockProvider with seed={seed}")

    async def generate_async(
        self,
        prompt: Union[str, List[Dict[str, str]]],
        tools: Optional[List[BaseTool]] = None,
        **kwargs
    ) -> str:
        """
        Generate a mock response based on the prompt.

        Args:
            prompt: String prompt or list of message dictionaries
            tools: Optional list of tools (not used in this implementation)
            **kwargs: Additional parameters (ignored in mock)

        Returns:
            A predefined, scripted, or random mock response
        """
        prompt_text = self._prompt_to_string(prompt)
        
        # Track the call for testing and debugging
        self.call_history.append({
            "method": "generate_async", 
            "prompt": prompt_text,
            "kwargs": kwargs
        })
        
        # Check for scripted responses first
        for key, response in self.scripted_responses.items():
            if key in prompt_text:
                logger.debug(f"Found scripted response for key: {key}")
                return response
        
        # Otherwise return a random canned response
        return random.choice(self.responses)

    async def generate_with_tools_async(
        self,
        conversation: List[Dict[str, str]],
        tools: List[BaseTool],
        **kwargs
    ) -> Dict[str, Any]:
        """
        Generate a mock response that may include tool calls.

        This implementation uses patterns in the conversation to determine
        whether to include tool calls or just return content.

        Args:
            conversation: List of conversation messages with 'role' and 'content'
            tools: List of tools available for the model to use
            **kwargs: Additional parameters (ignored in mock)

        Returns:
            Dictionary with 'content' and possibly 'tool_calls'
        """
        conv_text = self._conversation_to_string(conversation)
        
        # Track the call for testing and debugging
        self.call_history.append({
            "method": "generate_with_tools_async", 
            "conversation": conv_text,
            "tools": [t.name for t in tools],
            "kwargs": kwargs
        })
        
        # Check for scripted responses first
        for key, response in self.scripted_responses.items():
            if key in conv_text:
                # If the scripted response is a dictionary, use it directly
                if isinstance(response, dict):
                    logger.debug(f"Found scripted response object for key: {key}")
                    return response
                # Otherwise treat it as content without tool calls
                logger.debug(f"Found scripted content for key: {key}")
                return {"content": response, "tool_calls": []}
        
        # Determine if we should use a tool based on the conversation
        tool_calls = []
        available_tool_names = [tool.name for tool in tools]
        
        # Pattern matching for common tool-use scenarios
        tool_patterns = {
            "WebSearchTool": r'search|find|lookup|google|research|information about',
            "FileReaderTool": r'read file|open file|get content|load file',
            "FileWriterTool": r'write file|save file|create file|output to',
            "BrowserTool": r'browse|visit|navigate|website|url'
        }
        
        # Check if we should trigger a tool call
        should_use_tool = False
        
        # 1. Check for tool name mentions
        for tool_name in available_tool_names:
            if tool_name in conv_text:
                should_use_tool = True
                chosen_tool = tool_name
                break
                
        # 2. Check for action patterns
        if not should_use_tool:
            for tool_name, pattern in tool_patterns.items():
                if re.search(pattern, conv_text, re.IGNORECASE) and tool_name in available_tool_names:
                    should_use_tool = True
                    chosen_tool = tool_name
                    break
        
        # 3. Random chance of using a tool (about 30% if tools available)
        if not should_use_tool and tools and random.random() < 0.3:
            should_use_tool = True
            chosen_tool = random.choice(available_tool_names)
            
        # If we should use a tool, prepare the tool call
        if should_use_tool:
            # Get or create a tool call template
            if chosen_tool in self.tool_calls:
                tool_call = self.tool_calls[chosen_tool].copy()
            else:
                # Generic tool call template if we don't have a specific one
                tool_call = {
                    "name": chosen_tool,
                    "arguments": {"arg1": "value1"}
                }
                
            # Add a unique ID
            tool_call["id"] = f"mock-call-{random.randint(1000, 9999)}"
            tool_calls.append(tool_call)
            
            # With tool calls, we might have partial content
            content = "I need to use a tool to help with this." 
        else:
            # No tool calls, just return a response
            content = random.choice(self.responses)
            
        return {"content": content, "tool_calls": tool_calls}

    def _prompt_to_string(self, prompt: Union[str, List[Dict[str, str]]]) -> str:
        """
        Convert various prompt formats to a single string for matching.
        
        Args:
            prompt: Either a string prompt or a list of message dictionaries
            
        Returns:
            A string representation of the prompt
        """
        if isinstance(prompt, str):
            return prompt
        elif isinstance(prompt, list):
            # Convert a list of message dictionaries to a string
            return "\n".join(f"{msg.get('role', 'unknown')}: {msg.get('content', '')}" for msg in prompt)
        return str(prompt)

    def _conversation_to_string(self, conversation: List[Dict[str, str]]) -> str:
        """
        Convert a conversation to a single string for pattern matching.
        
        Args:
            conversation: List of conversation message dictionaries
            
        Returns:
            A string representation of the conversation
        """
        return "\n".join(f"{msg.get('role', 'unknown')}: {msg.get('content', '')}" for msg in conversation)
